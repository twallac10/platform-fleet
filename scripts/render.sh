#!/usr/bin/env bash
# Generate the per-tier and per-app Flux wiring from tiers.yaml and apps.yaml:
#   clusters/<tier>/platform.yaml   root Kustomization for ./fleet with TIER=<tier>
#   fleet/apps/<app>.yaml           GitRepository + Kustomization (./tiers/${TIER})
#   fleet/canary.yaml               Kustomization for ./canary
#   fleet/promoter.yaml             in-cluster promoter (+ Grafana Secret access)
#   promoter/gates.yaml             one PromotionGate per app
#   fleet/kustomization.yaml
# Output is committed; `task lint` fails if it is stale. Adding a tier or an
# app is: edit the YAML, run `task fleet:render`, commit.
set -euo pipefail
cd "$(dirname "$0")/.."
owner=$(yq '.owner' apps.yaml)
hdr="# Generated by scripts/render.sh from tiers.yaml/apps.yaml. Do not edit."

deps() { # deps <yq-path>: render a dependsOn list (or nothing)
  local n; n=$(yq "$1 | length" apps.yaml)
  [ "$n" -gt 0 ] || return 0
  echo "  dependsOn:"
  yq "$1[]" apps.yaml | sed 's/^/    - name: /'
}

for tier in $(yq '.tiers[].name' tiers.yaml); do
  mkdir -p "clusters/$tier"
  cat > "clusters/$tier/platform.yaml" <<YAML
$hdr
# Everything the $tier cluster runs, besides Flux itself (clusters/$tier/flux-system,
# written by flux bootstrap).
apiVersion: kustomize.toolkit.fluxcd.io/v1
kind: Kustomization
metadata:
  name: platform
  namespace: flux-system
spec:
  interval: 10m
  retryInterval: 1m
  path: ./fleet
  prune: true
  sourceRef:
    kind: GitRepository
    name: flux-system
  postBuild:
    substitute:
      TIER: $tier
YAML
done
# Remove clusters/<tier> for tiers no longer in tiers.yaml (only our file).
for d in clusters/*/; do
  t=$(basename "$d")
  yq -e ".tiers[] | select(.name == \"$t\")" tiers.yaml >/dev/null 2>&1 || rm -f "$d/platform.yaml"
done

rm -rf fleet/apps; mkdir -p fleet/apps
names=()
for i in $(seq 0 $(( $(yq '.apps | length' apps.yaml) - 1 ))); do
  name=$(yq ".apps[$i].name" apps.yaml); repo=$(yq ".apps[$i].repo" apps.yaml)
  names+=("$name")
  {
    cat <<YAML
$hdr
# $name: deployed from github.com/$owner/$repo, path ./tiers/\${TIER}.
apiVersion: source.toolkit.fluxcd.io/v1
kind: GitRepository
metadata:
  name: $name
  namespace: flux-system
spec:
  interval: 1m
  url: https://github.com/$owner/$repo
  ref:
    branch: main
---
apiVersion: kustomize.toolkit.fluxcd.io/v1
kind: Kustomization
metadata:
  name: $name
  namespace: flux-system
  labels:
    platform.twallac10.io/app: $name
spec:
YAML
    deps ".apps[$i].dependsOn"
    cat <<YAML
  interval: 10m
  retryInterval: 1m
  timeout: 10m
  path: ./tiers/\${TIER}
  prune: true
  wait: true
  sourceRef:
    kind: GitRepository
    name: $name
YAML
  } > "fleet/apps/$name.yaml"
done

{
  cat <<YAML
$hdr
# Canary tenant: not promoted, identical in every tier. Exercises the platform
# so the evidence gate has something real to check.
apiVersion: kustomize.toolkit.fluxcd.io/v1
kind: Kustomization
metadata:
  name: canary
  namespace: flux-system
spec:
YAML
  deps ".canary.dependsOn"
  cat <<YAML
  interval: 10m
  retryInterval: 1m
  timeout: 5m
  path: ./canary
  prune: true
  wait: true
  sourceRef:
    kind: GitRepository
    name: flux-system
YAML
} > fleet/canary.yaml

# In-cluster promoter: deployed to every cluster, NOT itself gated (it produces
# the evidence; see NOTES.md). No dependsOn: it must be up before the apps it gates.
cat > fleet/promoter.yaml <<YAML
$hdr
apiVersion: kustomize.toolkit.fluxcd.io/v1
kind: Kustomization
metadata:
  name: promoter
  namespace: flux-system
spec:
  interval: 10m
  retryInterval: 1m
  timeout: 5m
  path: ./promoter
  prune: true
  wait: true
  sourceRef:
    kind: GitRepository
    name: flux-system
  postBuild:
    substitute:
      TIER: \${TIER}
    # CLUSTER_NAME: created per cluster by \`task up\` (a tier can have many clusters).
    substituteFrom:
      - kind: ConfigMap
        name: cluster-identity
---
# Lets the promoter read the Grafana admin Secret (one Secret, by name), once
# kube-prometheus-stack has created the monitoring namespace.
apiVersion: kustomize.toolkit.fluxcd.io/v1
kind: Kustomization
metadata:
  name: promoter-monitoring
  namespace: flux-system
spec:
  dependsOn:
    - name: promoter
    - name: kube-prometheus-stack
  interval: 10m
  retryInterval: 1m
  path: ./promoter-monitoring
  prune: true
  sourceRef:
    kind: GitRepository
    name: flux-system
YAML

# One PromotionGate per app; identical in every cluster (tier and cluster
# come from the operator's settings).
{
  echo "$hdr"
  first=1
  for name in "${names[@]}"; do
    [ $first -eq 1 ] || echo "---"
    first=0
    cat <<YAML
apiVersion: platform.twallac10.io/v1alpha1
kind: PromotionGate
metadata:
  name: $name
  namespace: promoter
spec:
  app: $name
YAML
  done
} > promoter/gates.yaml

{
  echo "$hdr"
  echo "apiVersion: kustomize.config.k8s.io/v1beta1"
  echo "kind: Kustomization"
  echo "resources:"
  for n in "${names[@]}"; do echo "  - apps/$n.yaml"; done
  echo "  - canary.yaml"
  echo "  - promoter.yaml"
} > fleet/kustomization.yaml
